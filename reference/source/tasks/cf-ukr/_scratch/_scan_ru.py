import re, sys, collections
# скан русских слов в готовом переводе (out/strings_ua.tsv или любом файле: путь аргументом)
path = sys.argv[1] if len(sys.argv) > 1 else 'out/strings_ua.tsv'
RU = r"\b(что|это|как|или|если|когда|только|всех|всем|может|можно|нужно|урона|урон|юнитов|юнита|юниту|юнит|юниты|здание|здания|зданий|башни|башня|атакует|получает|получают|наносит|нанести|противника|противников|противникам|врагов|враги|врагам|своей|своих|этого|этой|будет|после|через|между|нельзя|игрока|игроков|раунда|раунд|секунды|секунду|жизни|здоровья|цели|цель|союзник\w*|вражеск\w*|уменьшает|увеличивает|построить|улучшить|тренерует|тренирует|сейчас|следующий|цена|золота|каждый|каждого|каждой|который|которые|которых|вокруг|одного|одну|один|других|других|такой|тоже|ещё|очень|всегда|перед|против|время|раза|раз|вашей|ваших|вашего|вас|вы|ваш|ваша|ваше|свою|свои|его|ему|них|им|при|без|над|под|для|нет|уже|даёт|дает|длится|шанс\w*|скорость|скорости|дальний|нормальная|колющая|лёгкая|средняя|тяжёлая)\b"
rx = re.compile(RU, re.I)
c = collections.Counter()
rows = []
for ln in open(path, encoding='utf-8').read().split('\n')[1:]:
    p = ln.split('\t')
    if len(p) < 3:
        continue
    t = re.sub(r'\|c[0-9a-fA-F]{8}|\|r|\|n', ' ', p[2])
    ws = rx.findall(t)
    if ws:
        rows.append((p[0], ws))
        c.update(w.lower() for w in ws)
print('строк с русскими словами:', len(rows))
print(c.most_common(60))
print([(i, w[:3]) for i, w in rows[:25]])
