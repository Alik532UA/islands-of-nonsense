import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';

const RULES_PATH = resolve(import.meta.dirname, '../database.rules.json');
const VERSION_TS_PATH = resolve(import.meta.dirname, '../src/lib/net/rulesVersion.ts');

const STAMP_LENGTH = 12;

function computeSemanticHash(rulesJson) {
	// Deep clone and normalize
	const clone = JSON.parse(JSON.stringify(rulesJson));
	if (clone.rules?.__rulesVersion?.$v) {
		clone.rules.__rulesVersion.$v['.read'] = 'auth != null';
	}
	const canonical = JSON.stringify(clone);
	return createHash('sha256').update(canonical).digest('hex').slice(0, STAMP_LENGTH);
}

const isCheckOnly = process.argv.includes('--check');

if (!existsSync(RULES_PATH)) {
	console.error('❌ database.rules.json not found');
	process.exit(1);
}

const rawRules = readFileSync(RULES_PATH, 'utf8');
const rulesJson = JSON.parse(rawRules);
const stamp = computeSemanticHash(rulesJson);

const currentRuleStampMatch = rulesJson.rules?.__rulesVersion?.$v?.['.read']?.match(/\$v === '([a-f0-9]+)'/);
const currentRuleStamp = currentRuleStampMatch ? currentRuleStampMatch[1] : null;

let currentTsStamp = null;
if (existsSync(VERSION_TS_PATH)) {
	const tsContent = readFileSync(VERSION_TS_PATH, 'utf8');
	const tsMatch = tsContent.match(/RULES_STAMP = '([a-f0-9]+)'/);
	if (tsMatch) currentTsStamp = tsMatch[1];
}

if (isCheckOnly) {
	if (currentRuleStamp !== stamp || currentTsStamp !== stamp) {
		console.error(`❌ Rules stamp mismatch! Computed: ${stamp}, database.rules.json: ${currentRuleStamp}, rulesVersion.ts: ${currentTsStamp}`);
		console.error('Run "npm run rules:stamp" to synchronize.');
		process.exit(1);
	}
	console.log(`✅ Rules stamp verified: ${stamp}`);
	process.exit(0);
}

// Update database.rules.json
if (!rulesJson.rules.__rulesVersion) {
	rulesJson.rules.__rulesVersion = { $v: { '.read': 'auth != null' } };
}
rulesJson.rules.__rulesVersion.$v['.read'] = `auth != null && $v === '${stamp}'`;
writeFileSync(RULES_PATH, JSON.stringify(rulesJson, null, 2) + '\n', 'utf8');

// Update src/lib/net/rulesVersion.ts
const tsSource = `/**
 * SHA-256 semantic rules stamp and versioning constant.
 * Automatically generated by scripts/rules-stamp.mjs.
 */
export const RULES_VERSION = 1;
export const RULES_STAMP = '${stamp}';
`;
writeFileSync(VERSION_TS_PATH, tsSource, 'utf8');

console.log(`✅ Stamped rules version with hash: ${stamp}`);
